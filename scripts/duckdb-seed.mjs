// A pristine DuckDB file lets Wasm create private buffer-backed databases without OPFS or HTTP.
import { DuckDBInstance } from "@duckdb/node-api";
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
const directory = await mkdtemp(path.join(tmpdir(), "jocki-duckdb-seed-"));
try {
  const filename = path.join(directory, "empty.duckdb");
  const db = await DuckDBInstance.create(filename);
  const connection = await db.connect();
  await connection.run("CHECKPOINT");
  connection.closeSync();
  db.closeSync();
  const bytes = await readFile(filename);
  await writeFile(
    new URL("../packages/storage/empty-database.ts", import.meta.url),
    "// Generated by scripts/duckdb-seed.mjs using the official DuckDB engine. No application data.\nexport const emptyDatabaseBase64 = " +
      JSON.stringify(bytes.toString("base64")) +
      ";\n",
  );
} finally {
  await rm(directory, { recursive: true, force: true });
}
